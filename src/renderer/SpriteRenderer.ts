  /**
   * Renders a single matrix frame onto an offscreen canvas.
   */
  public static bakeFrame(width: number, height: number, frame: string[][]): HTMLCanvasElement {
    let canvas: HTMLCanvasElement;

    if (typeof document !== 'undefined' && document.createElement) {
      canvas = document.createElement('canvas');
    } else {
      // Mock canvas for Node/Vitest headless testing environments
      canvas = {
        width,
        height,
        getContext: () => ({
          imageSmoothingEnabled: false,
          fillStyle: '',
          fillRect: () => {},
          clearRect: () => {},
        }),
      } as unknown as HTMLCanvasElement;
    }

    canvas.width = width;
    canvas.height = height;

    const ctx = canvas.getContext?.('2d') as CanvasRenderingContext2D | null;
    if (ctx) {
      ctx.imageSmoothingEnabled = false;

      for (let r = 0; r < height; r++) {
        const row = frame[r];
        if (!row) continue;
        for (let c = 0; c < width; c++) {
          const char = row[c];
          if (char && char !== '.') {
            ctx.fillStyle = PALETTE_CHAR_MAP[char] || PALETTE.WHITE;
            ctx.fillRect(c, r, 1, 1);
          }
        }
      }
    }

    return canvas;
  }

  /**
   * Primary high-throughput drawing function.
   * Employs fast-path execution to bypass save/restore matrices for untransformed sprites.
   */
  public static draw(
    ctx: CanvasRenderingContext2D,
    spriteId: string,
    x: number,
    y: number,
    options?: DrawOptions
  ): void {
    if (!SpriteRenderer.isInitialized) {
      SpriteRenderer.initialize();
    }

    const frameIndex = options?.frame ?? 0;
    const cacheKey = SpriteRenderer.getCacheKey(spriteId, frameIndex);
    let cached = SpriteRenderer.cache.get(cacheKey);

    if (!cached) {
      let def = SpriteRenderer.definitions.get(spriteId);
      if (!def && spriteId === 'ZAKO_WING_0') {
        def = SpriteRenderer.definitions.get('ZAKO');
      }
      if (def) {
        const frame = def.frames[frameIndex] ?? def.frames[0] ?? [];
        cached = SpriteRenderer.bakeFrame(def.width, def.height, frame);
        SpriteRenderer.cache.set(cacheKey, cached);
      } else {
        return;
      }
    }

    const rotation = options?.rotation ?? 0;
    const scale = options?.scale ?? 1.0;
    const flipX = options?.flipX ?? false;
    const flipY = options?.flipY ?? false;
    const alpha = options?.alpha ?? 1.0;
    const anchorX = options?.anchorX ?? 0.5;
    const anchorY = options?.anchorY ?? 0.5;

    const w = cached.width * scale;
    const h = cached.height * scale;
    const originX = w * anchorX;
    const originY = h * anchorY;

    // Fast-path: No rotation, scale 1.0, no flip, full opacity
    if (rotation === 0 && scale === 1.0 && !flipX && !flipY && alpha >= 0.999) {
      const destX = Math.round(x - originX);
      const destY = Math.round(y - originY);
      ctx.drawImage(cached, destX, destY);
      return;
    }

    // Transformed path: Matrix transformations
    ctx.save();
    if (alpha < 1.0) {
      ctx.globalAlpha = Math.max(0, Math.min(1.0, alpha));
    }

    ctx.translate(Math.round(x), Math.round(y));

    if (rotation !== 0) {
      ctx.rotate(rotation);
    }

    if (flipX || flipY || scale !== 1.0) {
      ctx.scale(flipX ? -scale : scale, flipY ? -scale : scale);
    }

    ctx.drawImage(cached, -Math.round(originX), -Math.round(originY));
    ctx.restore();
  }

  /**
   * Renders procedural hexagonal/circular energetic kinetic barrier for Dreadnought tier when shield > 0.
   */
  public static drawShieldAura(
    ctx: CanvasRenderingContext2D,
    x: number,
    y: number,
    shield: number,
    shieldFlashTimer: number = 0,
    animTimer: number = 0
  ): void {
    if (shield <= 0) return;

    ctx.save();

    const isFlashing = shieldFlashTimer > 0;
    const pulseSpeed = isFlashing ? 24 : 8;
    const pulseOffset = Math.sin(animTimer * pulseSpeed);
    const baseRadius = 12 + pulseOffset * 0.8;
    const rot = animTimer * 1.5; // Smooth geometric rotation

    // 1. Strobe on projectile absorption vs idle shimmering
    if (isFlashing) {
      ctx.strokeStyle = '#FFFFFF';
      ctx.fillStyle = 'rgba(0, 255, 255, 0.40)';
      ctx.lineWidth = 2.0;
      ctx.shadowColor = '#00FFFF';
      ctx.shadowBlur = 6;
    } else {
      ctx.strokeStyle = '#00FFFF';
      ctx.fillStyle = 'rgba(0, 255, 255, 0.12)';
      ctx.lineWidth = 1.2;
      ctx.globalAlpha = 0.65 + 0.25 * Math.sin(animTimer * 10);
    }

    // 2. Primary Hexagonal Kinetic Barrier
    ctx.beginPath();
    for (let i = 0; i < 6; i++) {
      const angle = rot + (i * Math.PI) / 3;
      const vx = Math.round(x + baseRadius * Math.cos(angle));
      const vy = Math.round(y + baseRadius * Math.sin(angle));
      if (i === 0) {
        ctx.moveTo(vx, vy);
      } else {
        ctx.lineTo(vx, vy);
      }
    }
    ctx.closePath();
    ctx.fill();
    ctx.stroke();

    // 3. Multi-Layer Concentric Barrier for Heavy Shields (shield >= 2)
    if (shield >= 2) {
      const innerRadius = baseRadius - 3.5;
      const innerRot = -rot * 1.2;
      ctx.beginPath();
      for (let i = 0; i < 6; i++) {
        const angle = innerRot + (i * Math.PI) / 3;
        const vx = Math.round(x + innerRadius * Math.cos(angle));
        const vy = Math.round(y + innerRadius * Math.sin(angle));
        if (i === 0) {
          ctx.moveTo(vx, vy);
        } else {
          ctx.lineTo(vx, vy);
        }
      }
      ctx.closePath();
      ctx.stroke();
    }

    // 4. Orbital Energy Nodes at Hexagon Vertices
    if (!isFlashing) {
      ctx.fillStyle = '#FFFFFF';
      for (let i = 0; i < 6; i++) {
        const angle = rot + (i * Math.PI) / 3;
        const nx = Math.round(x + baseRadius * Math.cos(angle));
        const ny = Math.round(y + baseRadius * Math.sin(angle));
        ctx.fillRect(nx - 0.5, ny - 0.5, 1, 1);
      }
    }

    ctx.restore();
  }

  /**
   * Helper to draw enemy by type, anim frame, damage state, rotation, and tier/shield.
   */
  public static drawEnemy(
    ctx: CanvasRenderingContext2D,
    type: EnemyType,
    x: number,
    y: number,
    animFrame: number = 0,
    health: number = 1,
    rotation: number = 0,
    alpha: number = 1.0,
    tier: StageTier = 'CLASSIC',
    shield: number = 0,
    damageFlashTimer: number = 0,
    shieldFlashTimer: number = 0,
    animTimer: number = 0
  ): void {
    let spriteId: string;
    const isElite = tier === 'ELITE' || tier === 'DREADNOUGHT';

    // 1. Resolve Sprite Definition by Type, Tier & Health State
    switch (type) {
      case EnemyType.ZAKO:
        if (isElite) {
          // If damaged (1 HP left of 2), flash between elite and alert amber/classic at 8Hz
          const isFractured = health === 1;
          const flashPhase = Math.floor(animTimer * 16) % 2 === 0;
          spriteId = isFractured && flashPhase ? 'ZAKO' : 'ELITE_ZAKO';
        } else {
          spriteId = 'ZAKO';
        }
        break;

      case EnemyType.GOEI:
        if (isElite) {
          const isFractured = health === 1;
          const flashPhase = Math.floor(animTimer * 16) % 2 === 0;
          spriteId = isFractured && flashPhase ? 'GOEI' : 'ELITE_GOEI';
        } else {
          spriteId = 'GOEI';
        }
        break;

      case EnemyType.BOSS:
        if (health >= 3) {
          spriteId = 'BOSS_ELITE';   // Imperial Golden Flagship
        } else if (health === 2) {
          spriteId = 'BOSS_HEALTHY'; // Standard Green Carapace
        } else {
          spriteId = 'BOSS_DAMAGED'; // Wounded Blue Carapace
        }
        break;

      case EnemyType.CAPTURED_FIGHTER:
        spriteId = 'CAPTURED_FIGHTER';
        break;

      case EnemyType.TRANSFORM:
        spriteId = 'TRANSFORM_SCORPION';
        break;

      default:
        spriteId = 'ZAKO';
        break;
    }

    // 2. 80ms Arcade Hit Flash Override
    if (damageFlashTimer > 0 && shield <= 0) {
      if (type === EnemyType.BOSS) {
        spriteId = 'BOSS_FLASH';
      } else if (type === EnemyType.GOEI) {
        spriteId = 'GOEI_FLASH';
      } else {
        spriteId = 'ZAKO_FLASH';
      }
    }

    // 3. Draw Core Sprite
    SpriteRenderer.draw(ctx, spriteId, x, y, {
      frame: animFrame % 2,
      rotation,
      alpha,
    });

    // 4. Render Kinetic Shield Aura (if active)
    if (shield > 0) {
      SpriteRenderer.drawShieldAura(ctx, x, y, shield, shieldFlashTimer, animTimer);
    }
  }

